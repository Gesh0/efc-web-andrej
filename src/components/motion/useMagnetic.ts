"use client";

import { useEffect, type RefObject } from "react";

/**
 * Element drifts toward the pointer while hovered and springs back on leave.
 * Fine pointers only; no-op under reduced motion.
 */
export default function useMagnetic<T extends HTMLElement>(
  ref: RefObject<T | null>,
  strength = 0.22,
) {
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (
      !window.matchMedia("(hover: hover) and (pointer: fine)").matches ||
      window.matchMedia("(prefers-reduced-motion: reduce)").matches
    )
      return;
    el.style.transition = "transform 450ms cubic-bezier(.23,1,.32,1)";
    const move = (e: PointerEvent) => {
      const r = el.getBoundingClientRect();
      const x = (e.clientX - r.left - r.width / 2) * strength;
      const y = (e.clientY - r.top - r.height / 2) * strength;
      el.style.transform = `translate(${x.toFixed(1)}px, ${y.toFixed(1)}px)`;
    };
    const leave = () => {
      el.style.transform = "";
    };
    el.addEventListener("pointermove", move);
    el.addEventListener("pointerleave", leave);
    return () => {
      el.removeEventListener("pointermove", move);
      el.removeEventListener("pointerleave", leave);
    };
  }, [ref, strength]);
}
